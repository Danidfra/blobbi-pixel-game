const ok = (r: ReturnType<typeof resolveBlobbi>): BlobbiSource => {
  if (!r.ok) throw new Error(r.error);
  return r.source;
};
const error = (r: ReturnType<typeof resolveBlobbi>): string => (r.ok ? '' : r.error);

describe('Blobbi V3 identity: pubkey + d, V3 seeds and demo seeds', () => {
  it('derives the kit\'s frozen seed for every address vector (the d tag exactly as given: no trimming, no Unicode folding)', () => {
    for (const v of VECTORS) expect(ok(resolveBlobbi({ pubkey: v.pubkey, d: v.d }))).toEqual({ kind: 'v3-address', pubkey: v.pubkey, d: v.d, seed: v.seed });
  });

  it('a 64-hex V3 seed is used as is, read in lower case (one spelling, the same Blobbi)', () => {
    const v = VECTORS[3];
    expect(ok(resolveBlobbi({ seed: v.seed }))).toEqual({ kind: 'v3-seed', seed: v.seed });
    const upper = resolveBlobbi({ seed: v.seed.toUpperCase() });
    expect(ok(upper)).toEqual({ kind: 'v3-seed', seed: v.seed });
    expect(upper.ok && upper.notes.join()).toMatch(/lower case/);
    expect(blobbiIdentity(ok(upper).seed).genome).toEqual(blobbiIdentity(v.seed).genome);
  });

  it('demo seeds keep working, unchanged: the same genome and sprite as before M3.4', () => {
    for (const seed of [DEMO_BLOBBI_SEED, 'abc123', 'blobbi-3', 'pip-1a2b']) {
      const s = ok(resolveBlobbi({ seed }));
      expect(s).toEqual({ kind: 'demo', seed });
      expect(blobbiIdentity(s.seed).genome).toEqual(generateGenome(seed));
    }
    expect(sourceFromSeed('blobbi-9')).toEqual({ kind: 'demo', seed: 'blobbi-9' });
    expect(sourceFromSeed(VECTORS[0].seed)).toEqual({ kind: 'v3-seed', seed: VECTORS[0].seed });
  });

  it('an address is the same Blobbi as in the Standalone: the kit\'s V3 identity of its seed agrees gene for gene', () => {
    for (const v of VECTORS.slice(0, 5)) {
      const source = ok(resolveBlobbi({ pubkey: v.pubkey, d: v.d }));
      const genome = blobbiIdentity(source.seed).genome;
      // What the Standalone resolves for a V3 event at this address (renderer `createBlobbiV3Identity`, as in
      // nostr-pet's `getBlobbiVisualIdentity` → `resolveBlobbiV3Visual`).
      const standalone = createBlobbiV3Identity(v.seed);
      expect(standalone.seed).toBe(source.seed);
      expect(standalone.colors).toEqual({ base: genome.colors.base, secondary: genome.colors.secondary, eye: genome.colors.eye, ...(genome.colors.accent ? { accent: genome.colors.accent } : {}) });
      const t = genome.traits;
      expect(standalone.traits).toEqual({
        antenna: (['none', 'single', 'double'] as const)[t.antenna.count],
        horns: t.horns.kind,
        ears: t.ears.kind,
        tail: t.tail.kind,
        pattern: t.pattern.kind,
        specialMark: t.mark.kind,
        belly: t.belly.enabled,
        freckles: t.freckles.enabled,
      });
      // And the genome is exactly the kit's generator on that seed (what the Standalone draws from).
      expect(genome).toEqual(generateGenome(v.seed));
    }
  });

  it('refuses invalid input with a clear reason, and never repairs it into another Blobbi', () => {
    const pk = VECTORS[3].pubkey;
    const d = VECTORS[3].d;
    expect(error(resolveBlobbi({ seed: '' }))).toMatch(/empty/);
    expect(error(resolveBlobbi({ seed: ` ${VECTORS[0].seed}` }))).toMatch(/spaces/);
    expect(error(resolveBlobbi({ seed: 'blobbi-9 ' }))).toMatch(/spaces/);
    expect(error(resolveBlobbi({ seed: `0x${VECTORS[0].seed}` }))).toMatch(/0x/);
    expect(error(resolveBlobbi({ seed: VECTORS[0].seed.slice(1) }))).toMatch(/exactly 64 .* 63/);
    expect(error(resolveBlobbi({ seed: `${VECTORS[0].seed}0` }))).toMatch(/exactly 64 .* 65/);
    expect(error(resolveBlobbi({ pubkey: pk, d: '' }))).toMatch(/d tag is missing/);
    expect(error(resolveBlobbi({ pubkey: '', d }))).toMatch(/pubkey is missing/);
    expect(error(resolveBlobbi({ pubkey: 'npub1sg6plzptd64u62a878hep2kev88swjh3tw00gjsfl8f237lmu63q0uf63m', d }))).toMatch(/not an npub/);
    expect(error(resolveBlobbi({ pubkey: pk.toUpperCase(), d }))).toMatch(/lower case/);
    expect(error(resolveBlobbi({ pubkey: pk.slice(2), d }))).toMatch(/64 hexadecimal digits; this one has 62/);
    expect(error(resolveBlobbi({ pubkey: `${pk.slice(1)}g`, d }))).toMatch(/hexadecimal/);
    expect(error(resolveBlobbi({ pubkey: ` ${pk}`, d }))).toMatch(/spaces/);
    expect(error(resolveBlobbi({ pubkey: pk, d: 'blobbi-\ud800' }))).toMatch(/well-formed/);
    expect(error(resolveBlobbi({ seed: 'blobbi-9', pubkey: pk, d }))).toMatch(/not both/);
  });

  it('accepts a non-canonical d tag (the kit does) but says so; notes a d tag of another owner', () => {
    const r = resolveBlobbi({ pubkey: VECTORS[4].pubkey, d: 'x' });
    expect(r.ok && r.notes.join()).toMatch(/not in the canonical form/);
    const other = resolveBlobbi({ pubkey: VECTORS[2].pubkey, d: VECTORS[2].d });
    expect(other.ok && other.notes.join()).toMatch(/different owner prefix/);
    const canonical = resolveBlobbi({ pubkey: VECTORS[3].pubkey, d: VECTORS[3].d });
    expect(canonical.ok && canonical.notes).toEqual([]);
  });

  it('a V3 Blobbi is drawn at 12, 24 and 48 px from the one genome', () => {
    const id = blobbiIdentity(ok(resolveBlobbi({ pubkey: VECTORS[0].pubkey, d: VECTORS[0].d })).seed);
    for (const size of [12, 24, 48]) expect(buildBlobbiSprite(id, REST_POSE, size).buffer.opaqueCount()).toBeGreaterThan(size * size * 0.4);
  });
});

describe('persisting the selected Blobbi', () => {
  it('round-trips every kind of source, and a reload draws the same Blobbi', () => {
    const sources: BlobbiSource[] = [ok(resolveBlobbi({ pubkey: VECTORS[3].pubkey, d: VECTORS[3].d })), ok(resolveBlobbi({ seed: VECTORS[1].seed })), ok(resolveBlobbi({ seed: 'blobbi-9' }))];
    for (const s of sources) {
      const store = memoryStore();
      storeSelection(store, s);
      const loaded = loadSelection(store)!;
      expect(loaded).toEqual(s);
      // A new page: a new world built from the stored selection has the same genome.
      const live = new LiveWorld(generateTurtleWorld('turtle-0'), loaded, 16, { store });
      expect(live.blobbi.source).toEqual(s);
      expect(live.blobbi.identity.genome).toEqual(generateGenome(s.seed));
    }
  });

  it('ignores a missing, malformed or tampered record whole (a seed that its address does not derive)', () => {
    const store = memoryStore();
    expect(loadSelection(store)).toBeNull();
    for (const raw of ['{', '{"version":2,"source":{"kind":"demo","seed":"x"}}', '{"version":1,"source":{"kind":"v3-seed","seed":"zz"}}', '{"version":1,"source":{"kind":"other","seed":"x"}}']) {
      store.set(SELECTION_KEY, raw);
      expect(loadSelection(store), raw).toBeNull();
    }
    const real = ok(resolveBlobbi({ pubkey: VECTORS[3].pubkey, d: VECTORS[3].d }));
    store.set(SELECTION_KEY, JSON.stringify({ version: 1, source: { ...real, seed: VECTORS[0].seed } }));
    expect(loadSelection(store)).toBeNull();
    // A v3-seed record whose seed is not canonical (upper case) is not silently re-spelled.
    store.set(SELECTION_KEY, JSON.stringify({ version: 1, source: { kind: 'v3-seed', seed: VECTORS[0].seed.toUpperCase() } }));
    expect(loadSelection(store)).toBeNull();
  });

  it('the world owns the island and its inventory: switching Blobbis keeps them, and no save names a Blobbi', () => {
    const store = memoryStore();
    const world = generateTurtleWorld('turtle-0');
    const a = new LiveWorld(world, ok(resolveBlobbi({ seed: 'blobbi-9' })), 16, { store });
    a.inventory.add(ITEMS.stick.id, 3);
    a.save();
    const before = store.get(saveKey(a.identity));
    const v3 = ok(resolveBlobbi({ pubkey: VECTORS[3].pubkey, d: VECTORS[3].d }));
    a.setBlobbi(v3);
    expect(a.blobbi.source).toEqual(v3);
    expect(a.inventory.count(ITEMS.stick.id)).toBe(3);
    a.save();
    // The same record, under the same world key: nothing in it changed because the Blobbi did.
    expect(store.get(saveKey(a.identity))).toBe(before);
    const record = JSON.parse(before!);
    expect(record.owner).toBe(WORLD_OWNER);
    expect(JSON.stringify(record)).not.toContain('blobbi-9');
    expect(JSON.stringify(record)).not.toContain(v3.seed);
    expect([...store.data.keys()].every((k) => !k.includes(v3.seed) && !k.includes('blobbi-9'))).toBe(true);
    // Another Blobbi opening this world sees the world's inventory, by design and explicitly.
    const b = new LiveWorld(world, v3, 16, { store });
    expect(b.inventory.count(ITEMS.stick.id)).toBe(3);
    expect(worldIdentity(world)).not.toContain(v3.seed);
  });

  it('migrates schema 1-4 world records to schema 5 with the owner stated; refuses another owner', () => {
    const store = memoryStore();
    const world = generateTurtleWorld('turtle-0');
    const identity = worldIdentity(world);
    const v4 = { version: 4, world: identity, collected: [], inventory: { version: 1, context: identity, revision: 1, items: [{ item: ITEMS.stone.id, quantity: 2 }] }, equipped: null, trees: {}, worldTime: 12, buildings: [], collectedAt: {}, rocks: {} };
    store.set(saveKey(identity), JSON.stringify(v4));
    const migrated = loadSave(store, identity)!;
    expect(migrated.version).toBe(SAVE_VERSION);
    expect(migrated.owner).toBe('local-world');
    expect(migrated.inventory.items).toEqual(v4.inventory.items);
    expect(migrated.worldTime).toBe(12);
    // The next save writes schema 5 and keeps everything.
    const live = new LiveWorld(world, 'blobbi-9', 16, { store });
    live.save();
    const written = JSON.parse(store.get(saveKey(identity))!);
    expect(written).toMatchObject({ version: 5, owner: 'local-world', inventory: { items: v4.inventory.items } });
    store.set(saveKey(identity), JSON.stringify({ ...written, owner: 'blobbi:abc' }));
    expect(loadSave(store, identity)).toBeNull();
    store.set(saveKey(identity), JSON.stringify({ ...written, owner: undefined }));
    expect(loadSave(store, identity)).toBeNull();
  });

  it('camera modes never touch identity: the Blobbi, its genome and the stored selection are the same in every mode', () => {
    const store = memoryStore();
    const v3 = ok(resolveBlobbi({ pubkey: VECTORS[0].pubkey, d: VECTORS[0].d }));
    storeSelection(store, v3);
    const selection = store.get(SELECTION_KEY);
    const world = generateTurtleWorld('turtle-0');
    const live = new LiveWorld(world, v3, 16, { store });
    const view = new ViewRenderer(live, new LiveRenderer(live));
    const bounds = worldBounds(world);
    const camera = new ViewCamera('overview');
    for (let i = 0; i < 6; i++) {
      camera.cycle();
      const v = camera.update(1 / 60, { x: live.blobbi.x, y: live.blobbi.y, size: live.blobbi.size }, 480, 270, bounds, true);
      view.render(v, camera.restScale(camera.mode, 480, 270, bounds), live.clock.time, DEFAULT_LIVE_OPTIONS);
      expect(live.blobbi.source).toEqual(v3);
      expect(live.blobbi.seed).toBe(v3.seed);
      expect(view.lastBlobbi!.sprite.buffer.data).toEqual(buildBlobbiSprite(blobbiIdentity(v3.seed), live.blobbi.animator.pose(live.clock.time), view.lastBlobbi!.size).buffer.data);
    }
    expect(store.get(SELECTION_KEY)).toBe(selection);
  });
});
